import 'package:liz/shared/models/tool.dart';

/// A published tool with sensible defaults, for tests that care about one or
/// two fields.
Tool sampleTool({
  String id = 't-1',
  String name = 'Sample',
  String? slug,
  String tagline = 'Does one thing well',
  PricingType pricing = PricingType.freemium,
  double momentum = 0,
  String? trendReason,
  int? trendRank,
  String? ghRepo,
  int? ghStars,
  String? hnId,
  int? hnPoints,
  int? hnComments,
  int ratingCount = 0,
  double avgRating = 0,
  DateTime? createdAt,
}) {
  return Tool(
    id: id,
    name: name,
    slug: slug ?? name.toLowerCase().replaceAll(' ', '-'),
    tagline: tagline,
    description: '$name. $tagline.',
    aiSummary: const [],
    websiteUrl: 'https://example.com',
    logoUrl: null,
    category: 'new-apps',
    tags: const [],
    platforms: const ['web'],
    pricingType: pricing,
    priceNote: null,
    source: 'test',
    sourceUrl: null,
    launchedAt: null,
    trendScore: 0,
    viewCount: 0,
    saveCount: 0,
    avgRating: avgRating,
    ratingCount: ratingCount,
    status: PublishStatus.published,
    createdAt: createdAt ?? DateTime(2026, 9, 20),
    trendRank: trendRank,
    momentum: momentum,
    trendReason: trendReason,
    ghRepo: ghRepo,
    ghStars: ghStars,
    hnId: hnId,
    hnPoints: hnPoints,
    hnComments: hnComments,
  );
}
